// Generates every WebSuli app icon from the approved robot artwork.
// Spec: docs/specs/2026-10-13-robot-ikon.md
// Usage (from source/): node scripts/generate-app-icons.mjs
// Needs Playwright's Chromium once per machine: npx playwright install chromium
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const PUBLIC = fileURLToPath(new URL("../client/public/", import.meta.url));

const DEFS = `
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#fb923c"/>
      <stop offset="1" stop-color="#ea580c"/>
    </linearGradient>
    <linearGradient id="head" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff"/>
      <stop offset="1" stop-color="#fef3e8"/>
    </linearGradient>
  </defs>`;

const ROBOT = `
    <!-- antenna -->
    <rect x="244" y="70" width="24" height="62" rx="12" fill="#ffffff"/>
    <circle cx="256" cy="70" r="30" fill="#fde047" stroke="#ffffff" stroke-width="10"/>
    <!-- ears -->
    <rect x="62" y="226" width="52" height="104" rx="26" fill="#ffffff"/>
    <rect x="398" y="226" width="52" height="104" rx="26" fill="#ffffff"/>
    <!-- head + face screen -->
    <rect x="96" y="126" width="320" height="292" rx="96" fill="url(#head)"/>
    <rect x="136" y="178" width="240" height="178" rx="70" fill="#1e293b"/>
    <!-- eyes -->
    <ellipse cx="204" cy="252" rx="30" ry="36" fill="#67e8f9"/>
    <ellipse cx="308" cy="252" rx="30" ry="36" fill="#67e8f9"/>
    <circle cx="214" cy="240" r="11" fill="#ffffff"/>
    <circle cx="318" cy="240" r="11" fill="#ffffff"/>
    <!-- smile + cheeks -->
    <path d="M214 304 Q256 340 298 304" fill="none" stroke="#67e8f9" stroke-width="16" stroke-linecap="round"/>
    <ellipse cx="160" cy="316" rx="20" ry="13" fill="#fb7185" opacity="0.85"/>
    <ellipse cx="352" cy="316" rx="20" ry="13" fill="#fb7185" opacity="0.85"/>`;

const svg = ({ radius, scale }) => `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
  <!-- WebSuli robot icon — generated by scripts/generate-app-icons.mjs -->${DEFS}
  <rect width="512" height="512" rx="${radius}" fill="url(#bg)"/>
  <g transform="translate(256 256) scale(${scale}) translate(-256 -256)">${ROBOT}
  </g>
</svg>
`;

// Rounded tile with transparent corners: browser tabs, PWA "any".
const ROUNDED = svg({ radius: 112, scale: 1 });
// Full-bleed square: iOS rounds it itself (transparent corners would turn black).
const APPLE = svg({ radius: 0, scale: 1 });
// Full-bleed with the robot inside the 80% maskable safe zone (Android adaptive icons).
const MASKABLE = svg({ radius: 0, scale: 0.8 });

const browser = await chromium.launch();
const page = await browser.newPage();
async function renderPng(markup, size) {
  await page.setViewportSize({ width: size, height: size });
  const src = `data:image/svg+xml;base64,${Buffer.from(markup).toString("base64")}`;
  await page.setContent(`<html><body style="margin:0;background:transparent"><img src="${src}" width="${size}" height="${size}" style="display:block"></body></html>`);
  await page.locator("img").evaluate((img) => img.decode());
  return page.screenshot({ omitBackground: true });
}

const outputs = [
  ["favicon.png", ROUNDED, 32],
  ["icon-192.png", ROUNDED, 192],
  ["icon-512.png", ROUNDED, 512],
  ["apple-touch-icon.png", APPLE, 180],
  ["icon-maskable-512.png", MASKABLE, 512],
];
for (const [name, markup, size] of outputs) {
  fs.writeFileSync(path.join(PUBLIC, name), await renderPng(markup, size));
}

// favicon.ico: ICONDIR + one ICONDIRENTRY per size, PNG-compressed images (supported since Vista).
const icoSizes = [16, 32, 48];
const images = [];
for (const size of icoSizes) images.push(await renderPng(ROUNDED, size));
await browser.close();

const header = Buffer.alloc(6 + 16 * images.length);
header.writeUInt16LE(0, 0); // reserved
header.writeUInt16LE(1, 2); // type: icon
header.writeUInt16LE(images.length, 4);
let offset = header.length;
images.forEach((png, i) => {
  const e = 6 + i * 16;
  header.writeUInt8(icoSizes[i], e); // width
  header.writeUInt8(icoSizes[i], e + 1); // height
  header.writeUInt8(0, e + 2); // palette colors
  header.writeUInt8(0, e + 3); // reserved
  header.writeUInt16LE(1, e + 4); // color planes
  header.writeUInt16LE(32, e + 6); // bits per pixel
  header.writeUInt32LE(png.length, e + 8);
  header.writeUInt32LE(offset, e + 12);
  offset += png.length;
});
fs.writeFileSync(path.join(PUBLIC, "favicon.ico"), Buffer.concat([header, ...images]));
fs.writeFileSync(path.join(PUBLIC, "favicon.svg"), ROUNDED);

console.log("icons written:", [...outputs.map(([n]) => n), "favicon.ico", "favicon.svg"].join(", "));
